from odoo import api, models
from odoo.tools.translate import LazyTranslate

_lt = LazyTranslate(__name__)
_lt_core = LazyTranslate('account_edi_ubl_cii')

# Plain lookup key: the name core gives to the substitute PDF of a vendor bill, translated through
# the catalog of the module that owns it.
CORE_GENERATED_PDF_NAME = _lt_core('%(invoice_name)s - Generated by Odoo', invoice_name='')
GENERATED_PDF_NAME = _lt('%(invoice_name)s - Generated by Viindoo', invoice_name='')


class IrAttachment(models.Model):
    _inherit = 'ir.attachment'

    @api.model_create_multi
    def create(self, vals_list):
        core_tail = brand_tail = None
        for vals in vals_list:
            name = vals.get('name')
            # The substitute PDF is created from the rendered report (`raw`); a PDF embedded in a
            # received XML is created from its encoded content (`datas`) under the sender's name.
            if not (
                vals.get('res_model') == 'account.move'
                and vals.get('mimetype') == 'application/pdf'
                and 'raw' in vals
                and name
            ):
                continue
            if core_tail is None:
                core_tail = CORE_GENERATED_PDF_NAME._translate(self.env.lang or 'en_US') + '.pdf'
                brand_tail = GENERATED_PDF_NAME._translate(self.env.lang or 'en_US') + '.pdf'
            if name.endswith(core_tail):
                vals['name'] = name[:-len(core_tail)] + brand_tail
        return super().create(vals_list)
