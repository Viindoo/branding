from odoo import api, models
from odoo.tools.translate import LazyTranslate

_lt = LazyTranslate(__name__)
# Core's own catalog: the name core gives to the substitute PDF of a vendor bill and the label it strips
# from the bill name are looked up there, never copied into this module.
_lt_core = LazyTranslate('account_edi_ubl_cii')


class IrAttachment(models.Model):
    _inherit = 'ir.attachment'

    @api.model
    def _get_substitute_pdf_names(self, move):
        """Return the name core gives to the PDF it generates for a vendor bill, and the Viindoo one.

        A PDF a vendor embeds in its document is named by the vendor, whereas the substitute PDF is
        the only one named after the bill of this database, so that name tells them apart.
        """
        # the msgids are in English: that is the language used when the environment has none
        lang = self.env.lang or 'en_US'
        invoice_name = move.display_name.replace(_lt_core('Draft')._translate(lang), '')
        core_name = _lt_core('%(invoice_name)s - Generated by Odoo', invoice_name=invoice_name)._translate(lang)
        brand_name = _lt('%(invoice_name)s - Generated by Viindoo', invoice_name=invoice_name)._translate(lang)
        return core_name + '.pdf', brand_name + '.pdf'

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            is_move_pdf = vals.get('res_model') == 'account.move' and vals.get('mimetype') == 'application/pdf'
            if not (is_move_pdf and vals.get('res_id') and vals.get('name')):
                continue
            move = self.env['account.move'].browse(vals['res_id'])
            if not (move.exists() and move.has_access('read')):
                continue
            core_name, brand_name = self._get_substitute_pdf_names(move)
            if vals['name'] == core_name:
                vals['name'] = brand_name
        return super().create(vals_list)
